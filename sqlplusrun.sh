#!/usr/bin/env bash

set -uo pipefail

# 1. ORACLE_HOME
if [[ -z "${ORACLE_HOME:-}" ]]; then
  printf "%s%03d\t%s\n" "W" "$LINENO" "\$ORACLE_HOME path is not set" >&2;
fi


# 2. SQLPLUS
if ! command -v sqlplus &>/dev/null; then
  printf "%s%03d\t%s\n" "E" "$LINENO" "sqlplus is NOT installed or NOT in \$PATH" >&2;
  exit 1;
fi


# 3. PATH
SQL_PATH="";
if [[ $# -gt 0 ]]; then
  if command -v realpath &>/dev/null; then
    if ! SQL_PATH=$( realpath -q -- "${1%/}" ); then
      printf "%s%03d\t%s\n" "E" "$LINENO" "cannot resolve path: ${1}" >&2
      exit 1
    fi
  else
    printf "%s%03d\t%s\n" "E" "$LINENO" "realpath is not available" >&2;
    exit 1;
  fi
else
  printf "%s%03d\t%s\n" "I" "$LINENO" "Usage: ./$(basename "${0}") <path>"
  exit 1
fi
if [[ ! -e "$SQL_PATH" ]]; then
    printf "%s%03d\t%s\n" "E" "$LINENO" "path not found: ${1}" >&2
    exit 1
fi

# 4. CONNECT
CONNECTION_STRING="";
if [[ -n "${SQLPLUSCONNECT:-}" ]]; then
 CONNECTION_STRING="${SQLPLUSCONNECT}";
else
  printf "%s%03d\t%s\n" "E" "$LINENO" "\$SQLPLUSCONNECT is not set, will not be able to connect" >&2;
  printf "%s%03d\t%s\n" "I" "$LINENO" "Usage: export SQLPLUSCONNECT=\"<connection>\"; ./$(basename "${0}") <path>"
  exit 1;
fi


# 5. DEFINE
SQL_DEFINE="";
while IFS='=' read -r -d '' env_key env_value; do
  if [[ "${env_key,,}" =~ ^(i_|v_|sql_) && ! "$env_key" =~ [$'\r\n'] && ! "$env_value" =~ [$'\r\n'] ]]; then
    env_key="${env_key//[^a-zA-Z0-9_]/}";
    env_key="${env_key:0:128}";
    env_value="${env_value:0:240}";
    env_value="${env_value//\'/\'\'}";
    SQL_DEFINE+=$'\n'"DEFINE ${env_key^^} = '${env_value}';"
  fi
done < <( env -0 );


# 6. FILES
SQL_FILE="";
if [[ -f "${SQL_PATH}" ]]; then
    SQL_FILE="@@\"${SQL_PATH}\""
fi
if [[ -d "${SQL_PATH}" ]]; then
  while read -r -d $'\0' SQLFILE; do
    if [[ -f "${SQLFILE}" ]]; then
      SQL_FILE+=$'\n'"@@\"${SQLFILE}\""
    fi
  done < <(find "${SQL_PATH}" -mindepth 1 \( -type d -name '.*' -prune \) -o \( -type f ! -name '.*' \( -iname '*.sql' -o -iname '*.pls' -o -iname '*.pck' -o -iname '*.pks' -o -iname '*.pkb' \) -print0 \) | sort --ignore-case --version-sort --zero-terminated);
fi
if [[ -z "${SQL_FILE}" ]]; then
  printf "%s%03d\t%s\n" "W" "$LINENO" "no files found" >&2;
  exit 1
fi

# 7. RUN
sqlplus -S -L /nolog <<EOF

REM  Performs the specified action (exits SQL*Plus by default) if an operating system error occurs (such as a file writing error).
WHENEVER OSERROR EXIT FAILURE ROLLBACK

REM  Performs the specified action (exits SQL*Plus by default) if a SQL command or PL/SQL block generates an error.
REM  EXIT SQL.SQLCODE could be converted to 0 by mistake, so better to use EXIT FAILURE
REM  WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
WHENEVER SQLERROR EXIT FAILURE ROLLBACK

REM  Controls whether SQL*Plus lists the old and new settings of a SQL*Plus system variable when you change the setting with SET.
SET SHOWMODE OFF

REM  Sets the total number of characters that SQL*Plus displays on one line before beginning a new line.
SET LINESIZE 100

REM  Controls whether to display output (that is, DBMS_OUTPUT.PUT_LINE) of stored procedures or PL/SQL blocks in SQL*Plus.
SET SERVEROUTPUT ON SIZE UNLIMITED FORMAT WORD_WRAPPED

REM  Controls when Oracle Database commits pending changes to the database.
REM SET AUTOCOMMIT OFF

REM  Displays the number of records returned by a script when a script selects at least n records.
REM SET FEEDBACK OFF

REM  Controls printing of column headings in reports.
REM SET HEADING OFF

REM  Controls the display of output generated by commands in a script that is executed with @, @@ or START.
REM SET TERMOUT ON

REM  Sets the number of lines on each page of output. You can set PAGESIZE to zero to suppress all headings, page breaks, titles, the initial blank line, and other formatting information.
REM  SET PAGESIZE 0
SET PAGESIZE 1000

REM  Determines whether SQL*Plus puts trailing blanks at the end of each spooled line.
SET TRIMSPOOL ON

REM  Controls whether to list the text of a SQL statement or PL/SQL command before and after replacing substitution variables with values.
SET VERIFY OFF

REM  Controls whether SQL*Plus truncates the display of a SELECTed row if it is too long for the current line width.
SET WRAP OFF

REM  Controls whether or not to echo commands in a script that is executed with @, @@ or START.
SET ECHO OFF

REM  Displays the elapsed execution time of each SQL statement or PL/SQL block.
SET TIMING ON

REM  Disables SQL*Plus substitution variables using & and &&.
SET DEFINE OFF

REM  Controls whether blank lines are allowed within SQL statements without terminating the statement.
SET SQLBLANKLINES ON

CONNECT ${CONNECTION_STRING}

ALTER SESSION SET RECYCLEBIN = OFF;

ALTER SESSION DISABLE PARALLEL DML;
ALTER SESSION DISABLE PARALLEL DDL;
-- ALTER SESSION DISABLE PARALLEL query;

${SQL_DEFINE}

SET DEFINE ON

${SQL_FILE}

REM  recompile whatever is invalid only
EXEC DBMS_UTILITY.COMPILE_SCHEMA(USER, FALSE);

COMMIT;

EXIT SUCCESS;

EOF


# 8. EXIT
sqlplus_rc=$?;
exit "$sqlplus_rc";
